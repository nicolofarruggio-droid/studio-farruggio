import { chromium } from '@playwright/test'
const dir = process.env.DIR
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1400, height: 1000 }, locale: 'it-IT', acceptDownloads: true })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
await page.goto('http://localhost:3000/accedi')
await page.getByLabel('Email').fill('giulia.verdi@studio-demo.it')
await page.getByLabel('Password', { exact: true }).fill('Prova-BigBrother-2026')
await page.getByRole('button', { name: 'Accedi', exact: true }).click()
await page.waitForURL('**/dashboard')
await page.goto('http://localhost:3000/clienti')
console.log('titolo:', await page.getByRole('heading', { level: 1 }).textContent())
const righe = await page.locator('tbody tr').count()
console.log('righe visibili a Giulia:', righe)
// aggiornamento rapido IVA della Pizzeria
await page.getByRole('button', { name: 'Aggiorna IVA di Pizzeria Da Gino' }).click()
