await page.waitForTimeout(1500)
console.log('toast:', await page.locator('[data-sonner-toast]').first().textContent())
// comunicazione manuale e email incollata
await page.getByRole('link', { name: 'Pizzeria Da Gino' }).click()
await page.waitForURL('**/clienti/*')
await page.getByLabel('Descrizione').fill('Incontro in studio per il bilancio.')
